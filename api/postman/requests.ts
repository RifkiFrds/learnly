/**
 * Definisi seluruh request Postman Learnly — satu sumber untuk folder per-modul & folder skenario.
 * Deskripsi ditulis untuk developer FE yang belum membaca dokumen teknis backend.
 */

export type Auth = 'none' | 'user' | 'tutor' | 'admin' | 'student';
type Method = 'GET' | 'POST' | 'PUT' | 'PATCH' | 'DELETE';

export interface RequestDef {
  key: string;
  folder: string;
  name: string;
  method: Method;
  path: string;
  query?: [string, string, string?][];
  auth: Auth;
  body?: unknown;
  description: string;
  /** status yang diharapkan (default 200, atau 201 jika `created`) */
  expect?: number;
  created?: boolean;
  /** env var → ekspresi JS terhadap `data` (json.data) yang disimpan otomatis setelah sukses */
  setVars?: Record<string, string>;
  test?: string[];
  pre?: string[];
}

export const NUM = '__NUM__';
/** Placeholder angka (ditulis tanpa tanda kutip di body JSON) */
const num = (name: string) => `${NUM}${name}`;

function doc(p: {
  what: string;
  when: string;
  who: string;
  after: string;
  errors?: [string, string][];
  notes?: string;
}) {
  const lines = [
    p.what,
    '',
    `**Kapan dipakai:** ${p.when}`,
    '',
    `**Siapa yang boleh:** ${p.who}`,
    '',
    `**Setelah sukses:** ${p.after}`,
  ];
  if (p.errors?.length) {
    lines.push(
      '',
      '**Kemungkinan error:**',
      ...p.errors.map(([code, text]) => `- \`${code}\` — ${text}`),
    );
  }
  if (p.notes) lines.push('', `**Catatan untuk FE:** ${p.notes}`);
  return lines.join('\n');
}

const E401 = [
  '401 UNAUTHENTICATED',
  'token tidak ada / kedaluwarsa (15 menit). Panggil Refresh Token lalu ulangi.',
] as [string, string];
const E403 = (who: string) =>
  ['403 FORBIDDEN', `akun yang login bukan ${who}, atau data ini bukan milikmu.`] as [
    string,
    string,
  ];
const E400 = [
  '400 VALIDATION_ERROR',
  'isian tidak valid — lihat `error.details[]` untuk field mana yang salah.',
] as [string, string];
const E404 = (what: string) => ['404 NOT_FOUND', `${what} tidak ditemukan.`] as [string, string];

/** Pre-request: hitung tanggal sesi (H+3, zona WIB) → {{bookingDate}} dan jam mulai tertentu */
const scheduleAt = (varName: string, hour: string) => [
  'const wib = new Date(Date.now() + 7 * 3600e3 + 3 * 86400e3);',
  'const date = wib.toISOString().slice(0, 10);',
  "pm.environment.set('bookingDate', date);",
  `pm.environment.set('${varName}', date + 'T${hour}:00+07:00');`,
];

const uniqueEmail = (varName: string, local: string) => [
  `pm.environment.set('${varName}', '${local}.' + Date.now() + '@contoh.id');`,
];

